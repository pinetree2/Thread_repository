def build_threads_prompt(
    topic: str,
    facts: list[str],
    sources: list[dict],
    language: str,
    style: str,
) -> str:
    return (
        f"TOPIC: {topic}\nOUTPUT_LANGUAGE: {language}\nCONTENT_STYLE: {style}\n"
        f"VERIFIED_FACTS:\n{json.dumps(facts, ensure_ascii=False, indent=2)}\n\n"
        f"FACT_SOURCES:\n{json.dumps(sources, ensure_ascii=False, indent=2)}\n\n"
        f"THREADS_SLANG_GUIDE:\n{json.dumps(THREADS_SLANG_GUIDE, ensure_ascii=False, indent=2)}\n\n"
        "요구사항: Threads Casual이면 hook을 '스친이들~', '스레더들~' 같은 친근한 도입으로 시작하되 매번 같은 표현을 반복하지 말라. "
        "hook은 첫 문장, body는 핵심 사실과 왜 중요한지를 적당히 상세하게 설명하라. "
        "body 마지막에는 '출처: 출처명' 형식으로 FACT_SOURCES 중 신뢰도 높은 출처 1~2개를 반드시 표시하라. "
        "근거 목록에 그대로 존재하지 않는 숫자는 사용하지 말고 숫자 없는 표현으로 바꿔라. "
        "ending은 '스친들은 어떻게 봄?', '이거 써본 스친 있음?'처럼 반말로 댓글을 자연스럽게 유도하라. "
        "hashtags는 2~4개로 하고 full_text 마지막에 포함하라. full_text는 그대로 게시 가능한 500자 이하 텍스트여야 한다."
    )
